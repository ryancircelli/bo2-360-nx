#if defined(__aarch64__) || defined(_M_ARM64)
namespace detail {
// VmxDot's portable arithmetic, two lanes per instruction: the same exact double products and the same
// addition order. FlushInSoftware is false when FPCR.FZ is set, because then the conversions themselves
// flush denormal inputs and a denormal result to a signed zero.
template <int Elements, bool FlushInSoftware>
inline simde__m128 VmxDotNeon(simde__m128 a, simde__m128 b) {
  const uint32x4_t exponent = vdupq_n_u32(0x7F800000u), sign = vdupq_n_u32(0x80000000u);
  uint32x4_t ab = vreinterpretq_u32_f32(simde__m128_to_neon_f32(a));
  uint32x4_t bb = vreinterpretq_u32_f32(simde__m128_to_neon_f32(b));
  if constexpr (FlushInSoftware) {  // keep the bits where the exponent is nonzero, else only the sign
    ab = vandq_u32(ab, vorrq_u32(vtstq_u32(ab, exponent), sign));
    bb = vandq_u32(bb, vorrq_u32(vtstq_u32(bb, exponent), sign));
  }
  const float32x4_t af = vreinterpretq_f32_u32(ab), bf = vreinterpretq_f32_u32(bb);
  // Host lane 3 - i is guest element i: lo = {p3, p2}, hi = {p1, p0}.
  const float64x2_t lo = vmulq_f64(vcvt_f64_f32(vget_low_f32(af)), vcvt_f64_f32(vget_low_f32(bf)));
  const float64x2_t hi = vmulq_f64(vcvt_high_f64_f32(af), vcvt_high_f64_f32(bf));
  float64x2_t sum;  // lane 0
  if constexpr (Elements == 3) {
    sum = vaddq_f64(vdupq_laneq_f64(vaddq_f64(hi, lo), 1), hi);  // (p0 + p2) + p1
  } else {
    const float64x2_t pairs = vaddq_f64(hi, lo);  // {p1 + p3, p0 + p2}
    sum = vpaddq_f64(pairs, pairs);
  }
  uint32x2_t bits = vreinterpret_u32_f32(vcvt_f32_f64(sum));
  if constexpr (FlushInSoftware)
    bits = vand_u32(bits, vorr_u32(vtst_u32(bits, vget_low_u32(exponent)), vget_low_u32(sign)));
  // An infinite or NaN result is QNaN unless the double sum was itself infinite.
  if ((~vget_lane_u32(bits, 0) & 0x7F800000u) == 0) [[unlikely]] {
    if (!std::isinf(vgetq_lane_f64(sum, 0))) return simde_mm_castsi128_ps(simde_mm_set1_epi32(0x7FC00000));
  }
  return simde__m128_from_neon_f32(vreinterpretq_f32_u32(vdupq_lane_u32(bits, 0)));
}
}  // namespace detail
#endif

// Xenon dot products accumulate in double precision in guest lane order,
// then narrow once. Finite overflow produces QNaN, which matters to callers
// using a maximum-float sentinel before their first search iteration.
// Keep this consistent with Interpreter::VmxDot.
template <int Elements>
inline simde__m128 VmxDot(simde__m128 a, simde__m128 b) {
  static_assert(Elements == 3 || Elements == 4);
#if defined(__aarch64__) || defined(_M_ARM64)
  using platform::FPSCRPlatform;
  if (FPSCRPlatform::getcsr() & FPSCRPlatform::FlushMask) return detail::VmxDotNeon<Elements, false>(a, b);
  return detail::VmxDotNeon<Elements, true>(a, b);
#else
  alignas(16) float av[4], bv[4];
  simde_mm_store_ps(av, a);
  simde_mm_store_ps(bv, b);
  double products[4]{};
  for (int i = 0; i < Elements; ++i) {
    uint32_t ab, bb;
    std::memcpy(&ab, &av[3 - i], sizeof(ab));
    std::memcpy(&bb, &bv[3 - i], sizeof(bb));
    if ((ab & 0x7F800000u) == 0) ab &= 0x80000000u;
    if ((bb & 0x7F800000u) == 0) bb &= 0x80000000u;
    float af, bf;
    std::memcpy(&af, &ab, sizeof(af));
    std::memcpy(&bf, &bb, sizeof(bf));
    products[i] = double(af) * double(bf);
  }
  const double sum = Elements == 3
                         ? (products[0] + products[2]) + products[1]
                         : (products[0] + products[2]) + (products[1] + products[3]);
  const float result = float(sum);
  uint32_t bits;
  std::memcpy(&bits, &result, sizeof(bits));
  if (std::isnan(result) || (std::isinf(result) && !std::isinf(sum)))
    bits = 0x7FC00000u;
  else if ((bits & 0x7F800000u) == 0)
    bits &= 0x80000000u;
  return simde_mm_castsi128_ps(simde_mm_set1_epi32(int32_t(bits)));
#endif
}

// Unsigned 32-bit saturating add
inline simde__m128i simde_mm_adds_epu32(simde__m128i a, simde__m128i b) {
  return simde_mm_add_epi32(
      a, simde_mm_min_epu32(simde_mm_xor_si128(a, simde_mm_cmpeq_epi32(a, a)), b));
}

// Signed 8-bit average (rounds towards zero)
inline simde__m128i simde_mm_avg_epi8(simde__m128i a, simde__m128i b) {
  simde__m128i c = simde_mm_set1_epi8(char(128));
  return simde_mm_xor_si128(c,
                            simde_mm_avg_epu8(simde_mm_xor_si128(c, a), simde_mm_xor_si128(c, b)));
}

// Signed 16-bit average
inline simde__m128i simde_mm_avg_epi16(simde__m128i a, simde__m128i b) {
  simde__m128i c = simde_mm_set1_epi16(short(32768));
  return simde_mm_xor_si128(c,
                            simde_mm_avg_epu16(simde_mm_xor_si128(c, a), simde_mm_xor_si128(c, b)));
}

// Signed 32-bit average
inline simde__m128i simde_mm_avg_epi32(simde__m128i a, simde__m128i b) {
  simde__m128i sum = simde_mm_add_epi32(simde_mm_srai_epi32(a, 1), simde_mm_srai_epi32(b, 1));
  return simde_mm_add_epi32(sum,
                            simde_mm_and_si128(simde_mm_or_si128(a, b), simde_mm_set1_epi32(1)));
}

// vexptefp: exp2 estimate with out-of-range handling (x>=128 -> +inf, x<=-127 -> 0, NaN -> NaN)
inline simde__m128 vexptefp_ps(simde__m128 x0) {
  simde__m128 x = simde_mm_min_ps(simde_mm_max_ps(x0, simde_mm_set1_ps(-127.0f)), simde_mm_set1_ps(128.0f));
  simde__m128 n = simde_mm_round_ps(x, SIMDE_MM_FROUND_TO_NEG_INF | SIMDE_MM_FROUND_NO_EXC);
  simde__m128 f = simde_mm_sub_ps(x, n);
  // 4th-order minimax polynomial for 2^f, f in [0,1), ~12-bit accuracy
  simde__m128 p = simde_mm_set1_ps(1.8775767e-3f);
  p = simde_mm_add_ps(simde_mm_mul_ps(p, f), simde_mm_set1_ps(8.9893397e-3f));
  p = simde_mm_add_ps(simde_mm_mul_ps(p, f), simde_mm_set1_ps(5.5826318e-2f));
  p = simde_mm_add_ps(simde_mm_mul_ps(p, f), simde_mm_set1_ps(2.4015361e-1f));
  p = simde_mm_add_ps(simde_mm_mul_ps(p, f), simde_mm_set1_ps(6.9315308e-1f));
  p = simde_mm_add_ps(simde_mm_mul_ps(p, f), simde_mm_set1_ps(1.0f));
  // 2^n via exponent bits; n=128 -> 0x7F800000 (+inf), n=-127 -> 0
  simde__m128i exp_bits = simde_mm_slli_epi32(simde_mm_add_epi32(simde_mm_cvttps_epi32(n), simde_mm_set1_epi32(127)), 23);
  simde__m128 r = simde_mm_mul_ps(p, simde_mm_castsi128_ps(exp_bits));
  // NaN input: max/min above would swallow it, so pass it through
  return simde_mm_blendv_ps(r, x0, simde_mm_cmpunord_ps(x0, x0));
}

// Convert unsigned 32-bit integers to floats
inline simde__m128 simde_mm_cvtepu32_ps_(simde__m128i src1) {
  simde__m128i xmm1 = simde_mm_add_epi32(src1, simde_mm_set1_epi32(127));
  simde__m128i xmm0 = simde_mm_slli_epi32(src1, 31 - 8);
  xmm0 = simde_mm_srli_epi32(xmm0, 31);
  xmm0 = simde_mm_add_epi32(xmm0, xmm1);
  xmm0 = simde_mm_srai_epi32(xmm0, 8);
  xmm0 = simde_mm_add_epi32(xmm0, simde_mm_set1_epi32(0x4F800000));
  simde__m128 xmm2 = simde_mm_cvtepi32_ps(src1);
  return simde_mm_blendv_ps(xmm2, simde_mm_castsi128_ps(xmm0), simde_mm_castsi128_ps(src1));
}

// Permute bytes from two vectors based on control vector
inline simde__m128i simde_mm_perm_epi8_(simde__m128i a, simde__m128i b, simde__m128i c) {
  simde__m128i d = simde_mm_set1_epi8(0xF);
  simde__m128i e = simde_mm_sub_epi8(d, simde_mm_and_si128(c, d));
  return simde_mm_blendv_epi8(simde_mm_shuffle_epi8(a, e), simde_mm_shuffle_epi8(b, e),
                              simde_mm_slli_epi32(c, 3));
}

// Unsigned 8-bit compare greater than
inline simde__m128i simde_mm_cmpgt_epu8(simde__m128i a, simde__m128i b) {
  simde__m128i c = simde_mm_set1_epi8(char(128));
  return simde_mm_cmpgt_epi8(simde_mm_xor_si128(a, c), simde_mm_xor_si128(b, c));
}

