// https://msdn.microsoft.com/en-us/library/windows/desktop/microsoft.directx_sdk.reference.xinputgetkeystroke(v=vs.85).aspx
u32 XamInputGetKeystroke_entry(u32 user_index, u32 flags, ppc_ptr_t<X_INPUT_KEYSTROKE> keystroke) {
  // https://github.com/CodeAsm/ffplay360/blob/master/Common/AtgXime.cpp
  // user index = index or XUSER_INDEX_ANY
  // flags = XINPUT_FLAG_GAMEPAD (| _ANYUSER | _ANYDEVICE)

  if (!keystroke) return X_ERROR_BAD_ARGUMENTS;
  auto* is = input_system();
  return user_keystrokes.Get(user_index, flags, keystroke,
      [is](uint32_t port, uint32_t options, X_INPUT_KEYSTROKE* output) {
        return is->GetKeystroke(port, options, output);
      });
}

// Same as non-ex, just takes a pointer to user index.
u32 XamInputGetKeystrokeEx_entry(mapped_u32 user_index_ptr, u32 flags,
                                 ppc_ptr_t<X_INPUT_KEYSTROKE> keystroke) {
  if (!user_index_ptr || !keystroke) return X_ERROR_BAD_ARGUMENTS;
  auto* is = input_system();
  return user_keystrokes.GetEx(user_index_ptr, flags, keystroke,
      [is](uint32_t port, uint32_t options, X_INPUT_KEYSTROKE* output) {
        return is->GetKeystroke(port, options, output);
      });
}

i32 XamUserGetDeviceContext_entry(u32 user_index, u32 unk, mapped_u32 out_ptr) {
  if (!out_ptr) return X_E_INVALIDARG;
  auto* is = input_system();
  uint32_t context = 0;
  const auto result = rex::input::ConnectedUserContext(user_index, context, [is](uint32_t port) {
    X_INPUT_CAPABILITIES capabilities{};
    return is->GetCapabilities(port, XINPUT_FLAG_GAMEPAD, &capabilities) == X_ERROR_SUCCESS;
  });
  *out_ptr = context;
  return result;
}

